#!/bin/bash

# ============================================
# Проверка открытого порта на сервере
# ============================================

# Задаем сервер и порт для проверки
SERVER="github.com"
PORT="22"

echo "Проверяю порт $PORT на сервере $SERVER..."

# netcat проверяет порт, заглушаем вывод ошибок
nc -zv $SERVER $PORT 2>/dev/null

# Проверяем код возврата
if [ $? -eq 0 ]; then
    echo "✅ Порт $PORT открыт. SSH работает!"
else
    echo "❌ Порт $PORT закрыт или сервер недоступен!"
fi
